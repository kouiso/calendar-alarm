import 'dart:ui' show Color;

/// `ArgonColors`は、アプリケーションで使用される色を定義したクラスです。
class ArgonColors {
  /// 黒色を表します。
  static const Color black = Color(0xFF000000);

  /// 白色を表します。
  static const Color white = Color(0xFFFFFFFF);

  /// 初期色を表します。
  static const Color initial = Color.fromRGBO(23, 43, 77, 1);

  /// プライマリ色を表します。
  static const Color primary = Color.fromRGBO(94, 114, 228, 1);

  /// セカンダリ色を表します。
  static const Color secondary = Color.fromRGBO(247, 250, 252, 1);

  /// ラベル色を表します。
  static const Color label = Color.fromRGBO(254, 36, 114, 1);

  /// 情報色を表します。
  static const Color info = Color.fromRGBO(17, 205, 239, 1);

  /// エラー色を表します。
  static const Color error = Color.fromRGBO(245, 54, 92, 1);

  /// 成功色を表します。
  static const Color success = Color.fromRGBO(45, 206, 137, 1);

  /// 警告色を表します。
  static const Color warning = Color.fromRGBO(251, 99, 64, 1);

  /// ヘッダー色を表します。
  static const Color header = Color.fromRGBO(82, 95, 127, 1);

  /// 画面背景色を表します。
  static const Color bgColorScreen = Color.fromRGBO(248, 249, 254, 1);

  /// 境界線色を表します。
  static const Color border = Color.fromRGBO(202, 209, 215, 1);

  /// 入力成功色を表します。
  static const Color inputSuccess = Color.fromRGBO(123, 222, 177, 1);

  /// 入力エラー色を表します。
  static const Color inputError = Color.fromRGBO(252, 179, 164, 1);

  /// ミュート色を表します。
  static const Color muted = Color.fromRGBO(136, 152, 170, 1);

  /// テキスト色を表します。
  static const Color text = Color.fromRGBO(50, 50, 93, 1);
}
