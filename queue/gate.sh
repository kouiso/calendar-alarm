#!/bin/bash
# one PR at a time: LOCAL-CHECK -> GATE -> squash merge with sha. Stops on first problem.
S=/tmp/claude-0/-home-user/c98a3d37-2e8b-5f9f-bf50-a9de72bb8786/scratchpad
R=repos/kouiso/calendar-alarm; EV=${EV:-061dffc219beb33576cf16623d26421408291809}
FOOT=$'\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'
bad() { echo "$1" | grep -q "secondary rate limit\|HTTP 4\|HTTP 5"; }
while IFS='|' read -r n sha rev cmd counts checks note; do
  [ -z "$n" ] && continue; short=${sha:0:7}
  st=""; for i in 1 2 3 4 5 6; do j=$(gh api $R/pulls/$n --jq '"\(.head.sha) \(.mergeable_state) \(.state)"'); set -- $j; [ "$2" != unknown ] && break; sleep 10; done
  [ "$1" != "$sha" ] && { echo "STOP #$n head moved to $1"; exit 1; }
  [ "$2" != clean ] && { echo "STOP #$n state $2"; exit 1; }
  unr=$(gh api $R/pulls/$n/ccr/review_threads | jq '[.[]?|select(.is_resolved==false)]|length'); [ "$unr" != 0 ] && { echo "STOP #$n unresolved $unr"; exit 1; }
  t=$(date -u +%FT%H:%MZ)
  img="https://raw.githubusercontent.com/kouiso/calendar-alarm/$EV/evidence/$n-$short.png"
  b1="LOCAL-CHECK | head $sha | $cmd | $counts | $t"$'\n\n'"証跡（画像）: https://github.com/kouiso/calendar-alarm/blob/$EV/evidence/$n-$short.png"$'\n\n'"![evidence $short]($img)$FOOT"
  o=$(gh api $R/issues/$n/comments -f body="$b1" --jq .html_url 2>&1|tail -1); echo "#$n LC $o"; bad "$o" && { echo STOP; exit 1; }; lc=$o; sleep 20
  b2="GATE | head $sha | review $rev (PASS, must 0) | evidence $lc | checks $checks at $t | deploy nothing (a merge to master builds the CI APK artifact only) | repo rule met (unresolved review threads 0) | changed after pass ${CHG:-none}"$'\n\n'"$note$FOOT"
  o=$(gh api $R/issues/$n/comments -f body="$b2" --jq .html_url 2>&1|tail -1); echo "#$n GATE $o"; bad "$o" && { echo STOP; exit 1; }; sleep 20
  o=$(gh api -X PUT $R/pulls/$n/merge -f merge_method=squash -f sha=$sha --jq '"\(.merged) \(.sha)"' 2>&1|tail -1); echo "#$n MERGE $o"; echo "$o" | grep -q '^true' || { sleep 10; m=$(gh api $R/pulls/$n --jq .merged); echo "#$n merged-check $m"; [ "$m" = true ] || { echo STOP; exit 1; }; }; sleep 25
done < $S/gate.tsv
echo ALLDONE
